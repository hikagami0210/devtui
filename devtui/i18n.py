def translate(locale, template, **values):
    return (JAPANESE.get(template, template) if locale == "ja" else template).format(**values)


def status_text(language, status):
    if status.startswith("exit "):
        return translate(language, "exit {code}", code=status[5:])
    return JAPANESE.get(status, status) if language == "ja" else status
